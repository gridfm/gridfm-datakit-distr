"""Catalog rows and the dataset card."""

from __future__ import annotations

from collections import Counter
from collections.abc import Mapping, Sequence
from typing import Any

import pyarrow as pa

from gridfm_datakit_distr.io import schema
from gridfm_datakit_distr.io.manifest import Manifest


def networks_table(
    passports: Sequence[Mapping[str, Any]], networks: Sequence[Mapping[str, Any]]
) -> pa.Table:
    """``catalog/networks`` from the passports of the dataset's networks (manifest order)."""
    by_id = {p["network_id"]: p for p in passports}
    rows = []
    for n in networks:
        p = by_id[n["network_id"]]
        rows.append(
            {
                "network_id": p["network_id"],
                "network_idx": n["network_idx"],
                "representation": n.get("representation"),
                "source": p["source"],
                "original_format": p["original_format"],
                "converter": p["converter"],
                "license": p["license"],
                "n_buses": p["counts"]["buses"],
                "n_nodes": p["counts"]["nodes"],
                "n_elements": p["counts"]["elements"],
                "neutral_representation": p["neutral_representation"],
                "has_split_phase": p["has_split_phase"],
                "s_base_va": float(p["s_base_va"]),
                "frequency_hz": float(p["frequency_hz"]),
                "engine_version": p["engine_version"],
                "passport_path": f"catalog/passports/{p['network_id']}.json",
                "source_sha256": p["checksums"]["source_manifest_sha256"],
            }
        )
    return pa.Table.from_pylist(rows, schema=schema.CATALOG_NETWORKS)


def dataset_card(
    manifest: Manifest,
    passports: Sequence[Mapping[str, Any]],
    statuses: Counter[str],
    opf_statuses: Counter[str] | None = None,
) -> str:
    """The dataset's ``README.md``; ``opf_statuses`` with OPF labels."""
    config = manifest.config
    name = config["dataset_name"]
    units = Counter(u.status for u in manifest.units.values())
    lines = [
        f"# {name}",
        "",
        "Power-flow dataset of three-phase unbalanced distribution networks generated by "
        f"gridfm-datakit-distr {manifest.versions.get('generator', '?')} "
        f"(schema {manifest.schema_version}). Data dictionary: `docs/manual/outputs.md` of the "
        "generator.",
        "",
        "## Networks",
        "",
        "| Network | Source | Licence | Nodes | Neutral |",
        "|---|---|---|---|---|",
    ]
    for p in passports:
        lines.append(
            f"| `{p['network_id']}` | {p['source']} | {p['license']} | {p['counts']['nodes']} | "
            f"{p['neutral_representation']} |"
        )
    total = sum(statuses.values())
    lines += [
        "",
        "## Contents",
        "",
        f"- Scenarios: {total} ("
        + ", ".join(f"{k} {v}" for k, v in sorted(statuses.items()))
        + ").",
        *(
            [
                "- OPF labels: "
                + ", ".join(f"{k} {v}" for k, v in sorted(opf_statuses.items()))
                + " (`opf/opf_meta`; OPF labels: `docs/manual/opf.md`)."
            ]
            if opf_statuses is not None
            else []
        ),
        *(
            [
                "- Dispatchable generators (`manifest.json` `networks[].dg`): "
                + "; ".join(_dg(n) for n in manifest.networks if "dg" in n)
                + "."
            ]
            if any("dg" in n for n in manifest.networks)
            else []
        ),
        f"- Work units: {sum(units.values())} ("
        + ", ".join(f"{k} {v}" for k, v in sorted(units.items()))
        + ").",
        f"- Variants per network: {config['variants']['n_variants']}; scenarios per variant: "
        f"{config['scenarios']['n_scenarios_per_variant']}; load profiles: "
        f"{config['scenarios']['profiles']['provider']}; controls: {config['controls']['mode']}.",
        f"- Seed {config['settings']['seed']}; config hash `{manifest.config_hash}`; the resolved "
        "config is in `manifest.json`.",
        "",
        "## Known limitations",
        "",
        "- Only `converged` scenarios have result rows; the others are listed in "
        "`scenarios/scenario_meta` with their status.",
        "- PV output uses a synthetic clear-sky shape without location or date.",
        "- Profile times are offsets from the start of the source profiles; no source is dated.",
        "",
        "## Citation",
        "",
    ]
    for citation in sorted({p["citation"] for p in passports}):
        lines.append(f"- {citation}")
    return "\n".join(lines) + "\n"


def _dg(network: Mapping[str, Any]) -> str:
    """One network's dispatchable generators: units and capacity, or the status without them."""
    dg = network["dg"]
    if dg["status"] != "ok":
        return f"`{network['network_id']}` none ({dg['status']})"
    return (
        f"`{network['network_id']}` {dg['n_units']} of {dg['p_max_w'] / 1e3:.4g} kW "
        f"(bound: {dg['binding']})"
    )
