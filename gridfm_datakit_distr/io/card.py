from typing import Any

import pyarrow as pa

from gridfm_datakit_distr.io import schema
from gridfm_datakit_distr.io.manifest import Manifest

# The default `der.pv.penetration`, compared by value; _PV_DENSITY's figures hold for it only.
_PV_DENSITY_SPEC = {"distribution": "uniform", "low": 0.0, "high": 0.8}
_PV_DENSITY = (
    "- PV density: the share of customers with PV is drawn per variant uniform on [0, 0.8) (the "
    "default), median 0.40. Electricity North West's 14 374 distribution substations with 5 or "
    "more customers have a median of 0.043 MCS-certified PV installations per customer (SP "
    "Electricity North West open data, MCS installations per substation), a lower bound since "
    "MCS certifies only part of the installations: the default's median is about 9 times it, "
    "and 32.5 % of its draws lie within the substations' 5-95 % range (0.003-0.263). The dataset "
    "therefore describes mostly networks with far more PV than today's. Hence frequent reverse "
    "flow: at the default config the load of most of the catalog's CSIRO networks, all feeders "
    "summed as at their substation, is negative at its 10th percentile over scenarios, against "
    "0.7 % of the substations "
    "Electricity North West monitors (SP Electricity North West open data, LV load duration "
    "curves)."
)
# The default `scenarios.profiles.synthetic.variant_scale`; _LOAD_LEVEL's figures hold for it only.
_LOAD_LEVEL_SPEC = {"distribution": "log_uniform", "low": 1 / 2.64, "high": 2.64}
_LOAD_LEVEL = (
    "- Load level: with synthetic loads, every nominal load of a variant is multiplied by one "
    "factor L, drawn per variant log-uniform on [1/2.64, 2.64] (the default, median 1) and "
    "recorded as `variant_scale` in `variants/variants.perturbation`; the networks whose nominal "
    "loads are measured (EDP) keep L = 1. The range is the widest measured spread of the peak "
    "load per customer across networks, relative to the median of the catalog's CSIRO networks "
    "at L = 1: the 99th percentile of the 15-minute load per housing unit of 24 residential LV "
    "feeders of FeederBW (Netze BW, Zenodo 10.5281/zenodo.17831177, CC BY 4.0) spans 0.38-2.58 "
    "times that median, the 5-95 % range of the 90th percentile of half-hourly load per "
    "customer at Electricity North West's substations 0.52-2.53 times (SP Electricity North "
    "West open data, LV load duration curves)."
)


def networks_table(
    passports: Sequence[Mapping[str, Any]], networks: Sequence[Mapping[str, Any]]
) -> pa.Table:
    """``catalog/networks`` from the passports of the dataset's networks (manifest order)."""
    by_id = {p["network_id"]: p for p in passports}
    rows = []
    for n in networks:
        p = by_id[n["network_id"]]
        rows.append(
            {
                "network_id": p["network_id"],
                "network_idx": n["network_idx"],
                "representation": n.get("representation"),
                "source": p["source"],
                "original_format": p["original_format"],
                "converter": p["converter"],
                "license": p["license"],
                "n_buses": p["counts"]["buses"],
                "n_nodes": p["counts"]["nodes"],
                "n_elements": p["counts"]["elements"],
                "neutral_representation": p["neutral_representation"],
                "has_split_phase": p["has_split_phase"],
                "s_base_va": float(p["s_base_va"]),
                "frequency_hz": float(p["frequency_hz"]),
                "engine_version": p["engine_version"],
                "passport_path": f"catalog/passports/{p['network_id']}.json",
                "source_sha256": p["checksums"]["source_manifest_sha256"],
            }
        )
    return pa.Table.from_pylist(rows, schema=schema.CATALOG_NETWORKS)


def dataset_card(
    manifest: Manifest,
    passports: Sequence[Mapping[str, Any]],
    statuses: Counter[str],
    opf_statuses: Counter[str] | None = None,
) -> str:
    """The dataset's ``README.md``; ``opf_statuses`` with OPF labels."""
    config = manifest.config
    name = config["dataset_name"]
    pvgis = [n["pvgis"] for n in manifest.networks if "pvgis" in n]
    units = Counter(u.status for u in manifest.units.values())
    lines = [
        f"# {name}",
        "",
        "Power-flow dataset of three-phase unbalanced distribution networks generated by "
        f"gridfm-datakit-distr {manifest.versions.get('generator', '?')} "
        f"(schema {manifest.schema_version}). Data dictionary: `docs/manual/outputs.md` of the "
        "generator.",
        "",
        "## Networks",
        "",
        "| Network | Source | Licence | Nodes | Neutral |",
        "|---|---|---|---|---|",
    ]
    for p in passports:
        lines.append(
            f"| `{p['network_id']}` | {p['source']} | {p['license']} | {p['counts']['nodes']} | "
            f"{p['neutral_representation']} |"
        )
    total = sum(statuses.values())
    lines += [
        "",
        "## Contents",
        "",
        f"- Scenarios: {total} ("
        + ", ".join(f"{k} {v}" for k, v in sorted(statuses.items()))
        + ").",
        *(
            [
                "- OPF labels: "
                + ", ".join(f"{k} {v}" for k, v in sorted(opf_statuses.items()))
                + " (`opf/opf_meta`; OPF labels: `docs/manual/opf.md`)."
            ]
            if opf_statuses is not None
            else []
        ),
        *(
            [
                "- Dispatchable generators (`manifest.json` `networks[].dg`): "
                + "; ".join(_dg(n) for n in manifest.networks if "dg" in n)
                + "."
            ]
            if any("dg" in n for n in manifest.networks)
            else []
        ),
        *(
            [
                "- PV output: hourly series of PVGIS 5.3 (`manifest.json` `networks[].pvgis`): "
                + "; ".join(_pvgis(manifest.networks))
                + f". {pvgis[0]['attribution']} ({pvgis[0]['source_url']})."
            ]
            if pvgis
            else []
        ),
        *([_PV_DENSITY] if config["der"]["pv"]["penetration"] == _PV_DENSITY_SPEC else []),
        *([_LOAD_LEVEL] if _default_load_level(config) else []),
        f"- Work units: {sum(units.values())} ("
        + ", ".join(f"{k} {v}" for k, v in sorted(units.items()))
        + ").",
        f"- Variants per network: {config['variants']['n_variants']}; scenarios per variant: "
        f"{config['scenarios']['n_scenarios_per_variant']}; load profiles: "
        f"{config['scenarios']['profiles']['provider']}; controls: {config['controls']['mode']}.",
        f"- Seed {config['settings']['seed']}; config hash `{manifest.config_hash}`; the resolved "
        "config is in `manifest.json`.",
        "",
        "## Known limitations",
        "",
        "- Only `converged` scenarios have result rows; the others are listed in "
        "`scenarios/scenario_meta` with their status.",
        (
            "- PV output: one hour of a PVGIS series at a location chosen in the config (no "
            "source gives the networks' locations), drawn per scenario for the whole network."
            if pvgis
            else "- PV output uses a synthetic clear-sky shape without location or date."
        ),
        "- Profile times are offsets from the start of the source profiles; no source is dated.",
        "",
        "## Citation",
        "",
    ]
    for citation in sorted({p["citation"] for p in passports}):
        lines.append(f"- {citation}")
    return "\n".join(lines) + "\n"


def _default_load_level(config: Mapping[str, Any]) -> bool:
    profiles = config["scenarios"]["profiles"]
    return bool(
        profiles["provider"] == "synthetic"
        and profiles["synthetic"]["variant_scale"] == _LOAD_LEVEL_SPEC
    )


def _dg(network: Mapping[str, Any]) -> str:
    """One network's dispatchable generators: units and capacity, or the status without them."""
    dg = network["dg"]
    if dg["status"] != "ok":
        return f"`{network['network_id']}` none ({dg['status']})"
    return (
        f"`{network['network_id']}` {dg['n_units']} of {dg['p_max_w'] / 1e3:.4g} kW "
        f"(bound: {dg['binding']})"
    )


def _pvgis(networks: Sequence[Mapping[str, Any]]) -> list[str]:
    """Each PVGIS series of the dataset: where, what PVGIS used, for which networks."""
    series: dict[str, tuple[Mapping[str, Any], list[str]]] = {}
    for n in networks:
        if "pvgis" in n:
            series.setdefault(n["pvgis"]["sha256"], (n["pvgis"], []))[1].append(n["network_id"])
    return [
        f"{r['latitude']}, {r['longitude']} ({r['timezone']}), {r['years'][0]}-{r['years'][1]}, "
        f"{r['radiation_db']} and {r['meteo_db']}, slope {r['slope_deg']:g}°, azimuth "
        f"{r['azimuth_deg']:g}° for " + ", ".join(f"`{i}`" for i in ids)
        for r, ids in series.values()
    ]
